"""11_runbook.py -- generate the operations runbook from the investigator's own rules, so docs never drift from code."""
import importlib.util, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sp = importlib.util.spec_from_file_location("inv", ROOT / "src" / "07_investigate.py")
inv = importlib.util.module_from_spec(sp); sp.loader.exec_module(inv)

STEPS = {
    "schema": ["Compare the last two schema versions of the feed and list added/removed/renamed fields.",
               "Check the checksum status of the affected deliveries.",
               "Open a Development ticket with the diff; tell the client a fix is being prepared."],
    "transport": ["Check whether other feeds from the same source also failed (source outage vs endpoint).",
                  "Re-trigger the delivery once; if it fails again, escalate to Operations.",
                  "Tell the client delivery is delayed and give the next checkpoint time."],
    "content": ["Measure which field is missing (artwork, schedule, IDs) using completeness by field.",
                "If artwork: request assets from the client; if schedule: refresh the EPG source.",
                "Escalate to Development only if the mapping itself is wrong."],
}
sym = {k: dict(family=f, weight=w) for k, (f, w) in inv.RULES.items()}
fam = {f: dict(owner=o, meaning=m, candidate_causes=c, steps=STEPS[f]) for f, (o, m, c) in inv.FAMILY_INFO.items()}
(ROOT / "outputs" / "runbook.json").write_text(json.dumps(dict(symptoms=sym, families=fam), indent=1))
md = ["# Runbook: feed incident triage", "", "_Generated by `src/11_runbook.py` from the investigator rules._", "",
      "## Symptoms and what they point to", "", "| Symptom | Family | Weight |", "|---|---|---|"]
md += [f"| `{k}` | {v['family']} | {v['weight']} |" for k, v in sym.items()]
for f, v in fam.items():
    md += ["", f"## {f.title()} — owner: {v['owner']}", "", f"**Meaning:** {v['meaning']}.", "",
           "**Candidate causes:** " + ", ".join(f"`{c}`" for c in v["candidate_causes"]), "", "**Steps:**"]
    md += [f"{i}. {s}" for i, s in enumerate(v["steps"], 1)]
md += ["", "## Resolve vs escalate", "", "Resolve in Operations when the family is transport and one retry succeeds; otherwise escalate to the owner above with the generated ticket."]
(ROOT / "docs" / "runbook.md").write_text("\n".join(md) + "\n")
print("runbook written")
